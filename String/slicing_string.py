str = 'Core Python'
# step size 1
print(str[0:9:1])
# step size 2
print(str[:9:2])

# entire data
print(str[::])

# start from 2 to 3
print(str[2:4:1])

# access entire step size 2
print(str[::2])

# access entire data starting from 2
print(str[2::])

# access start from str[0] to [3] step size 1
print(str[:4:])

# access start from str[-4] to str[-2] left to right
print(str[-4:-1])

# access start from str[-6] till end of the string
print(str[-6::])

